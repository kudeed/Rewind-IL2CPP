using Mono.Cecil;
using Mono.Cecil.Cil;
using Mono.Cecil.Rocks;

namespace Rewind.Output;

/// <summary>
/// The source decompiler treats conv.r4 on an already-float expression as
/// redundant, but a CLI evaluation stack can retain more precision. Make
/// every explicit single-precision conversion a call boundary in a temporary
/// copy used only for source export. Never rewrite the recovered DLL.
/// </summary>
internal sealed class SourceFloatBoundaries : IDisposable
{
    public const string HelperName = "__RewindPrecision";
    public const string HelperSource = """
        // Generated by Rewind: preserve explicit single-precision rounding.
        internal static class __RewindPrecision
        {
            [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
            internal static float Round(float value) { return (float)value; }
            // Unary negation is not subtraction from +0: signed zero differs.
            [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
            internal static float Negate(float value) { return -value; }
        }
        """ + "\n";

    private string? _tempDirectory;
    public string AssemblyPath { get; private set; }
    public int Calls { get; private set; }
    public int Negations { get; private set; }

    public SourceFloatBoundaries(string path, bool enabled)
    {
        AssemblyPath = path;
        if (!enabled) return;
        using var resolver = new DefaultAssemblyResolver();
        resolver.AddSearchDirectory(Path.GetDirectoryName(Path.GetFullPath(path))!);
        using var assembly = AssemblyDefinition.ReadAssembly(path, new ReaderParameters { InMemory = true, AssemblyResolver = resolver });
        ModuleDefinition module = assembly.MainModule;
        // Never accidentally bind to a user-defined helper.
        if (module.Types.Any(t => t.Namespace.Length == 0 && t.Name == HelperName))
            throw new InvalidDataException("Source precision helper name already exists in " + path);
        static IEnumerable<TypeDefinition> Types(IEnumerable<TypeDefinition> types)
        {
            foreach (var t in types)
            {
                yield return t;
                foreach (var n in Types(t.NestedTypes)) yield return n;
            }
        }
        var sites = Types(module.Types).SelectMany(t => t.Methods).Where(m => m.HasBody)
            .Select(m => (Method: m, Sites: m.Body.Instructions.Where(i => i.OpCode.Code == Code.Conv_R4).ToArray()))
            .Where(x => x.Sites.Length != 0).ToArray();
        if (sites.Length == 0) return;
        var holder = new TypeDefinition("", HelperName,
            TypeAttributes.NotPublic | TypeAttributes.Abstract | TypeAttributes.Sealed | TypeAttributes.BeforeFieldInit,
            module.TypeSystem.Object);
        module.Types.Add(holder);
        var round = new MethodDefinition("Round",
            MethodAttributes.Assembly | MethodAttributes.Static | MethodAttributes.HideBySig,
            module.TypeSystem.Single);
        round.ImplAttributes |= MethodImplAttributes.NoInlining;
        round.Parameters.Add(new ParameterDefinition("value", ParameterAttributes.None, module.TypeSystem.Single));
        holder.Methods.Add(round);
        var il = round.Body.GetILProcessor();
        il.Emit(OpCodes.Ldarg_0);
        il.Emit(OpCodes.Conv_R4);
        il.Emit(OpCodes.Ret);
        var negate = new MethodDefinition("Negate",
            MethodAttributes.Assembly | MethodAttributes.Static | MethodAttributes.HideBySig,
            module.TypeSystem.Single);
        negate.ImplAttributes |= MethodImplAttributes.NoInlining;
        negate.Parameters.Add(new ParameterDefinition("value", ParameterAttributes.None, module.TypeSystem.Single));
        holder.Methods.Add(negate);
        var nil = negate.Body.GetILProcessor();
        nil.Emit(OpCodes.Ldarg_0);
        nil.Emit(OpCodes.Neg);
        nil.Emit(OpCodes.Ret);
        foreach (var (m, instructions) in sites)
        {
            // Widen short branches before increasing instruction lengths.
            // Existing branch targets and exception boundaries remain attached
            // to their original instructions; the inserted call is on the
            // conversion's fallthrough edge, with identical stack height.
            m.Body.SimplifyMacros();
            var p = m.Body.GetILProcessor();
            // Only a neg immediately after conv.r4, with no alternate entry,
            // has the necessary proven stack type. Leave all other negs alone.
            var targets = m.Body.Instructions.SelectMany(i => i.Operand switch
            {
                Instruction target => new[] { target },
                Instruction[] many => many,
                _ => Array.Empty<Instruction>()
            }).ToHashSet();
            foreach (var handler in m.Body.ExceptionHandlers)
            {
                targets.Add(handler.TryStart);
                targets.Add(handler.HandlerStart);
                if (handler.FilterStart != null) targets.Add(handler.FilterStart);
            }
            foreach (Instruction i in instructions)
            {
                if (Environment.GetEnvironmentVariable("REWIND_NO_SOURCE_NEGATION") == null &&
                    i.Next is { OpCode.Code: Code.Neg } n && !targets.Contains(n))
                {
                    n.OpCode = OpCodes.Call;
                    n.Operand = negate;
                    Negations++;
                }
                p.InsertAfter(i, Instruction.Create(OpCodes.Call, round));
                Calls++;
            }
            m.Body.OptimizeMacros();
        }
        _tempDirectory = Path.Combine(Path.GetTempPath(), "rewind-source-" + Guid.NewGuid().ToString("N"));
        try
        {
            Directory.CreateDirectory(_tempDirectory);
            AssemblyPath = Path.Combine(_tempDirectory, Path.GetFileName(path));
            assembly.Write(AssemblyPath);
        }
        catch
        {
            Dispose();
            throw;
        }
    }

    public void Dispose()
    {
        if (_tempDirectory == null) return;
        Directory.Delete(_tempDirectory, recursive: true);
        _tempDirectory = null;
    }
}
