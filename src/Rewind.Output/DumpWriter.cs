using System.Text;
using Rewind.Metadata;
using Rewind.Model;

namespace Rewind.Output;

/// <summary>
/// Writes the whole model as one annotated C#-style listing: every type and member with its address, offset,
/// vtable slot and attributes. This is a map of the program, not compilable code.
/// </summary>
public sealed class DumpWriter(Il2CppModel model)
{
    private readonly BlobDecoder _blobs = new(model);

    public void Write(string path)
    {
        using var w = new StreamWriter(path, false, new UTF8Encoding(false), 1 << 16);
        w.WriteLine($"// Generated by rewind. Metadata v{MetaVersion.Describe(model.Version)}, " +
                    $"{model.Image.Format}/{model.Image.Arch}, image base 0x{model.Image.ImageBase:X}");
        if (model.UnityVersion is { } unity) w.WriteLine($"// Unity {unity}");
        w.WriteLine($"// {model.Assemblies.Length} assemblies, {model.Types.Length} types, {model.Methods.Length} methods");
        w.WriteLine();
        foreach (AssemblyModel asm in model.Assemblies)
            w.WriteLine($"// Assembly {asm.Index}: {asm.Name}, Version={asm.Version} ({asm.Types.Count} types)");

        foreach (AssemblyModel asm in model.Assemblies)
        {
            w.WriteLine();
            w.WriteLine("// " + new string('=', 100));
            w.WriteLine($"// Assembly: {asm.Name}");
            w.WriteLine("// " + new string('=', 100));
            foreach (string a in Attributes(asm, 0x20000001, -1)) w.WriteLine("[assembly: " + a[1..]);
            foreach (TypeDef type in asm.Types)
                if (type.DeclaringType == null)
                    WriteType(w, type, 0);
        }
    }

    private IEnumerable<string> Attributes(AssemblyModel asm, uint token, int legacyIndex)
    {
        List<CustomAttribute> list;
        try
        {
            list = _blobs.ReadAttributes(asm, token, legacyIndex);
        }
        catch (Exception)
        {
            yield break;
        }
        foreach (CustomAttribute a in list) yield return CSharpFormat.Attribute(a);
    }

    private static string GenericList(GenericParam[] parameters) =>
        parameters.Length == 0 ? "" : "<" + string.Join(", ", parameters.Select(p => p.Name)) + ">";

    private void WriteType(StreamWriter w, TypeDef type, int depth)
    {
        string pad = new('\t', depth);
        w.WriteLine();
        if (depth == 0) w.WriteLine($"// Namespace: {(type.Namespace.Length == 0 ? "<global>" : type.Namespace)}");
        foreach (string a in Attributes(type.Assembly, type.Token, type.CustomAttributeIndex)) w.WriteLine(pad + a);

        var header = new StringBuilder(pad);
        header.Append(CSharpFormat.TypeModifiers(type)).Append(' ').Append(CSharpFormat.TypeKeyword(type)).Append(' ');
        // Nested types repeat the enclosing type's generic parameters; show only the ones introduced here.
        int inherited = type.DeclaringType?.GenericParameters.Length ?? 0;
        GenericParam[] own = type.GenericParameters.Length > inherited ? type.GenericParameters[inherited..] : [];
        header.Append(TypeDef.StripArity(type.Name)).Append(GenericList(own));

        var bases = new List<string>();
        if (type.IsEnum)
        {
            if (type.EnumUnderlyingType != null && type.EnumUnderlyingType.ShortName != "int")
                bases.Add(type.EnumUnderlyingType.ShortName);
        }
        else
        {
            if (type.BaseType != null && !type.IsValueType && type.BaseType.DisplayName != "object")
                bases.Add(type.BaseType.DisplayName);
            foreach (TypeSig i in type.Interfaces) bases.Add(i.DisplayName);
        }
        if (bases.Count != 0) header.Append(" : ").Append(string.Join(", ", bases));

        header.Append($" // TypeDefIndex: {type.Index}, Token: 0x{type.Token:X8}");
        if (type.Sizes.InstanceSize != 0) header.Append($", Size: 0x{type.Sizes.InstanceSize:X}");
        w.WriteLine(header);
        w.WriteLine(pad + "{");

        string inner = pad + "\t";
        if (type.Fields.Length != 0)
        {
            w.WriteLine(inner + "// Fields");
            foreach (FieldDef f in type.Fields)
            {
                foreach (string a in Attributes(type.Assembly, f.Token, f.CustomAttributeIndex)) w.WriteLine(inner + a);
                var line = new StringBuilder(inner);
                if (type.IsEnum && f.IsStatic)
                {
                    object? v = _blobs.ReadFieldDefault(f);
                    line.Append(f.Name).Append(" = ").Append(v is EnumConstant e ? CSharpFormat.Constant(e.Value) : CSharpFormat.Constant(v)).Append(',');
                }
                else
                {
                    line.Append(CSharpFormat.FieldModifiers(f)).Append(' ').Append(f.Type.DisplayName).Append(' ').Append(f.Name);
                    if (f.HasDefault && f.IsLiteral) line.Append(" = ").Append(CSharpFormat.Constant(_blobs.ReadFieldDefault(f)));
                    line.Append(';');
                    if (!f.IsLiteral)
                    {
                        if (f.IsThreadStatic) line.Append(" // thread static");
                        else if (f.Offset >= 0)
                        {
                            // Struct field offsets are recorded relative to a boxed instance; show the in-place offset.
                            int offset = !f.IsStatic && type.IsValueType ? f.Offset - 2 * model.Image.PointerSize : f.Offset;
                            line.Append($" // 0x{offset:X}");
                        }
                    }
                }
                w.WriteLine(line);
            }
        }

        if (type.Properties.Length != 0)
        {
            w.WriteLine();
            w.WriteLine(inner + "// Properties");
            foreach (PropertyDef p in type.Properties)
            {
                MethodDef? accessor = p.Getter ?? p.Setter;
                if (accessor == null) continue;
                TypeSig propertyType = p.Getter != null
                    ? p.Getter.ReturnType
                    : p.Setter!.Parameters.Length != 0 ? p.Setter.Parameters[^1].Type : model.Sigs.Opaque(SigKind.Unknown, "?");
                foreach (string a in Attributes(type.Assembly, p.Token, p.CustomAttributeIndex)) w.WriteLine(inner + a);
                string mods = CSharpFormat.MethodModifiers(accessor);
                w.WriteLine($"{inner}{(mods.Length == 0 ? "" : mods + " ")}{propertyType.DisplayName} {p.Name} {{ " +
                            $"{(p.Getter != null ? "get; " : "")}{(p.Setter != null ? "set; " : "")}}}");
            }
        }

        if (type.Events.Length != 0)
        {
            w.WriteLine();
            w.WriteLine(inner + "// Events");
            foreach (EventDef e in type.Events)
            {
                string mods = e.Add != null ? CSharpFormat.MethodModifiers(e.Add) : "";
                w.WriteLine($"{inner}{(mods.Length == 0 ? "" : mods + " ")}event {e.Type.DisplayName} {e.Name};");
            }
        }

        if (type.Methods.Length != 0)
        {
            w.WriteLine();
            w.WriteLine(inner + "// Methods");
            foreach (MethodDef m in type.Methods)
            {
                w.WriteLine();
                var note = new StringBuilder(inner + "// ");
                if (m.Address != 0)
                {
                    note.Append($"VA: 0x{m.Address:X} RVA: 0x{m.Address - model.Image.ImageBase:X}");
                    if (model.MethodsByAddress.TryGetValue(m.Address, out List<MethodDef>? sharing) && sharing.Count > 1)
                        note.Append($" (code shared by {sharing.Count} methods)");
                }
                else note.Append("no body");
                if (m.HasSlot) note.Append($" Slot: {m.Slot}");
                note.Append($" Token: 0x{m.Token:X8}");
                w.WriteLine(note);
                foreach (string a in Attributes(type.Assembly, m.Token, m.CustomAttributeIndex)) w.WriteLine(inner + a);

                var sig = new StringBuilder(inner);
                string mods = CSharpFormat.MethodModifiers(m);
                if (mods.Length != 0) sig.Append(mods).Append(' ');
                if (!m.IsConstructor) sig.Append(m.ReturnType.DisplayName).Append(' ');
                sig.Append(m.Name == ".ctor" ? TypeDef.StripArity(type.Name) : m.Name);
                sig.Append(GenericList(m.GenericParameters)).Append('(');
                for (int i = 0; i < m.Parameters.Length; i++)
                {
                    ParamDef p = m.Parameters[i];
                    if (i != 0) sig.Append(", ");
                    sig.Append(CSharpFormat.ParameterPrefix(p)).Append(CSharpFormat.ParameterType(p)).Append(' ').Append(p.Name);
                    if (p.HasDefault) sig.Append(" = ").Append(CSharpFormat.Constant(_blobs.ReadParameterDefault(p)));
                }
                sig.Append(m.IsAbstract || m.Address == 0 ? ");" : ") { }");
                w.WriteLine(sig);
            }
        }

        foreach (TypeDef nested in type.NestedTypes) WriteType(w, nested, depth + 1);
        w.WriteLine(pad + "}");
    }
}
